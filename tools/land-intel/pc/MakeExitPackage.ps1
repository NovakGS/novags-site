<#
  Make EXIT Package
  Novak Geospatial Solutions(TM), a BUCK2NINETY LLC company

  Makes the EXIT Professional Real Estate version of a finished Land Intelligence job.
  Run Make Land Intel for the job first, then this.

  What it does:
    1. Lists the jobs in C:\NovakGS_Work\01_Active that have a Land Intelligence build
       (04_Deliverables\Land_Intel\land_intel.json), newest first, and asks which one.
    2. Suggests the listing name EXIT will see (from the build, with "Hunting" taken out) and lets
       you type a better one, such as "33-Acre Wooded Parcel (Dane Co, WI)".
    3. Copies the package files to G:\My Drive\EXIT Land Intelligence\<job> <listing name>\ with
       the EXIT package names:
         1 Essentials            stays  1 Essentials
         2 Hunting & Recreation  becomes 2 Country Property
         3 Buyer Due Diligence   stays  3 Buyer Due Diligence
         4 Stewardship           becomes 4 New Owner Stewardship
       In package 2 it renames the hunting files (Outdoor App Files, Country Property Map, Country
       Listing Graphics), renames the folders inside the app files zip, and changes the map's name
       inside the Google Earth file.
       The PDFs are not copied here: they get EXIT branding when the pages are built, and the
       branded copies are added to this folder then.
    4. Copies what the EXIT web pages are built from (land_intel.json, the map images, and the
       original PDFs) to G:\My Drive\EXIT Build Files\<job>\, which is never shared, and writes
       exit_job.json there.
    5. Opens the new EXIT folder.

  Then ask Claude to build the EXIT pages for the job.

  Running it again for the same job replaces the files in place, so Drive keeps the same file
  links. Nothing is ever deleted.

  First run (from anywhere): copies itself to C:\NovakGS_Work\99_Tools, writes its icon, and puts
  a Make EXIT Package shortcut on the desktop.

  Switches:  -Job 26-239   -Name "33-Acre Wooded Parcel (Dane Co, WI)"   -Force (replace without
             asking)   -Root C:\NovakGS_Work   -DriveRoot "G:\My Drive"   -Install (shortcut only)
#>
