function Get-PowerShellExe { return (Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe') }

function Write-Icon {
  $bytes = [Convert]::FromBase64String(($IconBase64 -replace '\s', ''))
  [IO.File]::WriteAllBytes($IconPath, $bytes)
}

function Get-ShortcutPath { return (Join-Path ([Environment]::GetFolderPath('Desktop')) "$AppName.lnk") }

function New-DesktopShortcut {
  $lnk = Get-ShortcutPath
  $sh = New-Object -ComObject WScript.Shell
  $sc = $sh.CreateShortcut($lnk)
  $sc.TargetPath = Get-PowerShellExe
  $sc.Arguments = ('-NoProfile -ExecutionPolicy Bypass -File "{0}"' -f $Installed)
  $sc.WorkingDirectory = $Tools
  $sc.IconLocation = "$IconPath,0"
  $sc.Description = 'Make the EXIT Professional Real Estate version of a Land Intelligence job'
  $sc.Save()
  return $lnk
}

function Install-Self {
  if (-not (Test-Path -LiteralPath $Tools)) { New-Item -ItemType Directory -Path $Tools | Out-Null }
  $here = $PSCommandPath
  if ($here -and -not [string]::Equals($here, $Installed, [StringComparison]::OrdinalIgnoreCase)) {
    Copy-Item -LiteralPath $here -Destination $Installed -Force
  }
  try { Unblock-File -LiteralPath $Installed } catch {}
  Write-Icon
  $lnk = New-DesktopShortcut
  Write-Host ("Installed to {0}" -f $Installed) -ForegroundColor Green
  Write-Host ("Desktop shortcut: {0}" -f (Split-Path $lnk -Leaf)) -ForegroundColor Green
  Write-Host ''
}

function Wait-Close { Write-Host ''; [void](Read-Host 'Press Enter to close') }

# ---------------------------------------------------------------- helpers
function Find-DriveRoot {
  if ($DriveRoot) {
    if (Test-Path -LiteralPath $DriveRoot) { return $DriveRoot }
    throw "Can't find $DriveRoot. Is Google Drive running?"
  }
  if (Test-Path -LiteralPath 'G:\My Drive') { return 'G:\My Drive' }
  foreach ($d in [IO.DriveInfo]::GetDrives()) {
    $p = Join-Path $d.Name 'My Drive'
    try { if (Test-Path -LiteralPath (Join-Path $p 'Land Intelligence')) { return $p } } catch {}
  }
  throw "Can't find Google Drive (G:\My Drive). Start Google Drive for desktop and run this again."
}

function Get-BuiltJobs {
  if (-not (Test-Path -LiteralPath $Active)) { throw "Can't find $Active." }
  $jobs = @()
  foreach ($f in (Get-ChildItem -LiteralPath $Active -Directory)) {
    $li = Join-Path $f.FullName '04_Deliverables\Land_Intel'
    $json = Join-Path $li 'land_intel.json'
    if (Test-Path -LiteralPath $json) {
      $num = ($f.Name -split '_')[0]
      $jobs += [pscustomobject]@{ Number = $num; Folder = $f.Name; LandIntel = $li; Json = $json; Built = (Get-Item -LiteralPath $json).LastWriteTime }
    }
  }
  return @($jobs | Sort-Object Built -Descending)
}

function Select-Job($jobs) {
  if ($jobs.Count -eq 0) { throw "No job in $Active has a Land Intelligence build yet. Run Make Land Intel first." }
  if ($Job) {
    $hit = @($jobs | Where-Object { $_.Number -eq $Job -or $_.Folder -eq $Job })
    if ($hit.Count -eq 0) { throw "No Land Intelligence build found for job $Job." }
    return $hit[0]
  }
  Write-Host 'Jobs with a Land Intelligence build (newest first):'
  $shown = [Math]::Min($jobs.Count, 12)
  for ($i = 0; $i -lt $shown; $i++) {
    Write-Host ('  {0,2}. {1}   (built {2:MMM d, h:mm tt})' -f ($i + 1), $jobs[$i].Folder, $jobs[$i].Built)
  }
  Write-Host ''
  $a = (Read-Host 'Which job? Type its number in the list or the job number [1]').Trim()
  if ($a -eq '') { return $jobs[0] }
  if ($a -match '^\d{1,2}$' -and [int]$a -ge 1 -and [int]$a -le $shown) { return $jobs[[int]$a - 1] }
  $hit = @($jobs | Where-Object { $_.Number -eq $a })
  if ($hit.Count -eq 0) { throw "No Land Intelligence build found for job $a." }
  return $hit[0]
}

function Get-DefaultName($title) {
  # "33-Acre Hunting Property, Dane County, WI" -> "33-Acre Country Property (Dane Co, WI)"
  $t = [string]$title
  $t = $t -replace 'Hunting (Property|Land)', 'Country Property'
  if ($t -match '^(.*?),\s*(.+?) County,\s*([A-Za-z]{2})$') { $t = '{0} ({1} Co, {2})' -f $Matches[1], $Matches[2], $Matches[3] }
  return $t
}

function Get-CleanName([string]$s) {
  $s = ($s -replace '[\\/:*?"<>|]', ' ') -replace '\s+', ' '
  return $s.Trim(' .')
}

function Get-ExitFileName([string]$pack, [string]$file) {
  if ($pack -ne '2') { return $file }
  $n = $file.Replace('Hunting App Files', 'Outdoor App Files').Replace('Hunting Listing Graphics', 'Country Listing Graphics')
  $n = $n -replace '^(\S+) Property Map \(Google Earth\)', '$1 Country Property Map (Google Earth)'
  return $n
}

function Copy-ZipRenamed([string]$Src, [string]$Dst, $NameMap, $TextMap) {
  # Rewrites a zip or KMZ entry by entry, in the same order, renaming entries with NameMap and
  # replacing words in .kml entries with TextMap. Written to a temp file first, then copied over
  # the destination so Drive keeps the same file.
  $tmp = Join-Path $env:TEMP ('ngs_' + [IO.Path]::GetRandomFileName() + '.zip')
  $in = [IO.Compression.ZipFile]::OpenRead($Src)
  try {
    $outStream = [IO.File]::Open($tmp, [IO.FileMode]::CreateNew)
    $out = New-Object IO.Compression.ZipArchive($outStream, [IO.Compression.ZipArchiveMode]::Create)
    try {
      foreach ($e in $in.Entries) {
        $name = $e.FullName
        foreach ($k in $NameMap.Keys) { $name = $name.Replace($k, $NameMap[$k]) }
        $ne = $out.CreateEntry($name, [IO.Compression.CompressionLevel]::Optimal)
        $ne.LastWriteTime = $e.LastWriteTime
        if ($name.EndsWith('/')) { continue }
        $r = $e.Open()
        $w = $ne.Open()
        try {
          if ($TextMap -and $TextMap.Count -gt 0 -and $name.ToLower().EndsWith('.kml')) {
            $ms = New-Object IO.MemoryStream
            $r.CopyTo($ms)
            $bytes = $ms.ToArray()
            $bom = ($bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF)
            $start = 0; if ($bom) { $start = 3 }
            $text = $Utf8.GetString($bytes, $start, $bytes.Length - $start)
            foreach ($k in $TextMap.Keys) { $text = $text.Replace($k, $TextMap[$k]) }
            if ($bom) { $w.Write([byte[]](0xEF, 0xBB, 0xBF), 0, 3) }
            $nb = $Utf8.GetBytes($text)
            $w.Write($nb, 0, $nb.Length)
          } else {
            $r.CopyTo($w)
          }
        } finally { $w.Dispose(); $r.Dispose() }
      }
    } finally { $out.Dispose(); $outStream.Dispose() }
  } finally { $in.Dispose() }
  Copy-Item -LiteralPath $tmp -Destination $Dst -Force
  Remove-Item -LiteralPath $tmp -Force
}

function Write-Json($obj, [string]$path) {
  [IO.File]::WriteAllText($path, ($obj | ConvertTo-Json -Depth 6), $Utf8)
}

# ---------------------------------------------------------------- the work
function Invoke-Main {
  $drive = Find-DriveRoot
  $jobs = @(Get-BuiltJobs)
  $j = Select-Job $jobs
  $li = Get-Content -LiteralPath $j.Json -Raw -Encoding UTF8 | ConvertFrom-Json
  $title = [string]$li.meta.title
  Write-Host ''
  Write-Host ('Job {0}: {1}' -f $j.Number, $title) -ForegroundColor Cyan

  $listing = $Name
  if (-not $listing) {
    $def = Get-DefaultName $title
    $a = (Read-Host ("Listing name EXIT will see [{0}]" -f $def)).Trim()
    if ($a -eq '') { $listing = $def } else { $listing = $a }
  }
  $listing = Get-CleanName $listing
  if ($listing.StartsWith($j.Number + ' ')) { $listing = $listing.Substring($j.Number.Length + 1) }
  $folderName = '{0} {1}' -f $j.Number, $listing

  $exitRoot = Join-Path $drive $ExitTop
  $dest = Join-Path $exitRoot $folderName
  $build = Join-Path (Join-Path $drive $BuildTop) $j.Number

  # One EXIT folder per job: reuse one made earlier under another listing name.
  if (Test-Path -LiteralPath $exitRoot) {
    $old = @(Get-ChildItem -LiteralPath $exitRoot -Directory | Where-Object { $_.Name.StartsWith($j.Number + ' ') -and $_.Name -ne $folderName })
    if ($old.Count -gt 0) {
      Write-Host ''
      Write-Host ('There is already an EXIT folder for this job: {0}' -f $old[0].Name) -ForegroundColor Yellow
      $a = (Read-Host 'Use that folder (keeps its name and links)? Y or N [Y]').Trim()
      if ($a -eq '' -or $a -match '^[Yy]') { $dest = $old[0].FullName; $folderName = $old[0].Name }
    }
  }
  if ((Test-Path -LiteralPath $dest) -and -not $Force) {
    $a = (Read-Host ('{0} already exists. Replace its files with this build? Y or N [Y]' -f $folderName)).Trim()
    if (-not ($a -eq '' -or $a -match '^[Yy]')) { Write-Host 'Stopped. Nothing was changed.'; return }
  }

  Write-Host ''
  Write-Host ('EXIT folder:  {0}' -f $dest)
  Write-Host ('Build files:  {0}' -f $build)
  Write-Host ''

  $packs = [ordered]@{}
  $pdfs = @()
  $kept = @()
  foreach ($src in (Get-ChildItem -LiteralPath $j.LandIntel -Directory | Where-Object { $_.Name -match '^[1-4] ' } | Sort-Object Name)) {
    $num = $src.Name.Substring(0, 1)
    $packName = $PackNames[$num]
    $outDir = Join-Path $dest $packName
    New-Item -ItemType Directory -Path $outDir -Force | Out-Null
    $list = @()
    foreach ($f in (Get-ChildItem -LiteralPath $src.FullName -File | Sort-Object Name)) {
      if ($f.Extension -ieq '.pdf') { $pdfs += [pscustomobject]@{ Pack = $packName; File = $f }; continue }
      $newName = Get-ExitFileName $num $f.Name
      $to = Join-Path $outDir $newName
      $ext = $f.Extension.ToLower()
      if ($num -eq '2' -and $ext -eq '.zip' -and $f.Name -like '*App Files*') {
        Copy-ZipRenamed $f.FullName $to $ZipNameMap $null
      } elseif ($num -eq '2' -and $ext -eq '.kmz') {
        Copy-ZipRenamed $f.FullName $to @{} $KmlTextMap
      } else {
        Copy-Item -LiteralPath $f.FullName -Destination $to -Force
      }
      if ($newName -match 'Hunting') { $kept += ('{0}\{1}' -f $packName, $newName) }
      $list += $newName
      Write-Host ('  copied  {0}\{1}' -f $packName, $newName)
    }
    $packs[$packName] = $list
  }
  if ($packs.Count -eq 0) { throw ("No package folders (1 Essentials ... 4 Stewardship) in {0}." -f $j.LandIntel) }

  # Build files: the job data, map images, and original PDFs. This folder is never shared.
  New-Item -ItemType Directory -Path (Join-Path $build 'images') -Force | Out-Null
  New-Item -ItemType Directory -Path (Join-Path $build 'pdfs') -Force | Out-Null
  Copy-Item -LiteralPath $j.Json -Destination (Join-Path $build 'land_intel.json') -Force
  $work = Join-Path $j.LandIntel '_work'
  $imgs = @()
  if (Test-Path -LiteralPath $work) {
    foreach ($p in (Get-ChildItem -LiteralPath $work -File -Filter '*.png')) {
      Copy-Item -LiteralPath $p.FullName -Destination (Join-Path (Join-Path $build 'images') $p.Name) -Force
      $imgs += $p.Name
    }
  }
  $pdfList = @()
  foreach ($p in $pdfs) {
    Copy-Item -LiteralPath $p.File.FullName -Destination (Join-Path (Join-Path $build 'pdfs') $p.File.Name) -Force
    $pdfList += [pscustomobject]@{ package = $p.Pack; file = $p.File.Name }
  }
  Write-Host ('  build files: land_intel.json, {0} map images, {1} PDFs' -f $imgs.Count, $pdfList.Count)

  $manifest = [ordered]@{
    job          = $j.Number
    job_folder   = $j.Folder
    title        = $title
    listing_name = $listing
    exit_folder  = ('{0}\{1}' -f $ExitTop, (Split-Path $dest -Leaf))
    acres        = $li.property.acres
    county       = $li.meta.county
    state        = $li.meta.state
    flight_dates = $li.meta.flight_dates
    land_intel_built = $li.meta.built
    made         = (Get-Date).ToString('yyyy-MM-dd HH:mm')
    packages     = $packs
    pdfs         = $pdfList
    images       = $imgs
  }
  Write-Json $manifest (Join-Path $build 'exit_job.json')

  Write-Host ''
  Write-Host 'Done.' -ForegroundColor Green
  Write-Host ('The EXIT folder has {0} files. The PDFs are added, with EXIT branding, when the pages are built.' -f (($packs.Values | ForEach-Object { $_.Count } | Measure-Object -Sum).Sum))
  foreach ($k in $kept) { Write-Host ('Check this name, it still says Hunting: {0}' -f $k) -ForegroundColor Yellow }
  Write-Host ('Next: ask Claude to build the EXIT pages for job {0}.' -f $j.Number)
  try { Start-Process -FilePath 'explorer.exe' -ArgumentList ('"{0}"' -f $dest) } catch {}
}

